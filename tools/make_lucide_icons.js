// Render only the pinned Lucide subset into a white, tintable WoW texture atlas.
// Build-only renderer, installed outside this repo:
//   npm install --prefix <renderer-dir> --no-save --package-lock=false @resvg/resvg-js@2.6.2
//   node tools/make_lucide_icons.js <renderer-dir>
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const source = path.join(__dirname, 'lucide');
const manifest = JSON.parse(fs.readFileSync(path.join(source, 'manifest.json'), 'utf8'));
if (!process.argv[2]) {
  console.error('usage: node tools/make_lucide_icons.js <renderer-dir>');
  process.exit(2);
}
const { Resvg } = require(require.resolve('@resvg/resvg-js', { paths: [path.resolve(process.argv[2])] }));
const { cellSize, columns, icons } = manifest;
const rows = 2 ** Math.ceil(Math.log2(Math.ceil(icons.length / columns)));
const width = columns * cellSize, height = rows * cellSize;
const pixels = Buffer.alloc(width * height * 4, 255);
for (let i = 3; i < pixels.length; i += 4) pixels[i] = 0;
for (let index = 0; index < icons.length; index++) {
  const svg = fs.readFileSync(path.join(source, 'icons', icons[index] + '.svg'), 'utf8');
  const image = new Resvg(svg.replace(/currentColor/g, '#ffffff'), { fitTo: { mode: 'width', value: cellSize } }).render();
  if (image.width !== cellSize || image.height !== cellSize) throw new Error('Unexpected icon size: ' + icons[index]);
  const rgba = image.pixels;
  const left = (index % columns) * cellSize, top = Math.floor(index / columns) * cellSize;
  for (let y = 0; y < cellSize; y++) for (let x = 0; x < cellSize; x++) {
    // White RGB and straight alpha avoid dark fringes when the game tints/scales the icons.
    pixels[((top + y) * width + left + x) * 4 + 3] = rgba[(y * cellSize + x) * 4 + 3];
  }
}
const header = Buffer.alloc(18);
header[2] = 2; // uncompressed true-color TGA; all RGB channels are white (BGRA == RGBA).
header.writeUInt16LE(width, 12); header.writeUInt16LE(height, 14);
header[16] = 32; header[17] = 0x28; // 8 alpha bits, top-left origin.
fs.writeFileSync(path.join(root, 'KutzUI/Media/Icons/lucide.tga'), Buffer.concat([header, pixels]));
const indexes = icons.map((name, index) => `    ["${name}"] = ${index},`).join('\n');
const lua = `-- Generated by tools/make_lucide_icons.js from the pinned Lucide subset. Do not edit.
-- Shared icon helpers allocate textures only when a module or settings window requests one.
local ADDON_NAME, ns = ...
local ATLAS = "Interface\\\\AddOns\\\\KutzUI\\\\Media\\\\Icons\\\\lucide.tga"
local INDEX = {
${indexes}
}
function ns.SetIcon(texture, name)
    local index = INDEX[name]
    if index == nil then return false end
    local column, row = index % ${columns}, math.floor(index / ${columns})
    texture:SetTexture(ATLAS)
    texture:SetTexCoord(column / ${columns}, (column + 1) / ${columns}, row / ${rows}, (row + 1) / ${rows})
    return true
end
function ns.CreateIcon(parent, name, size, layer)
    if INDEX[name] == nil then return nil end
    local texture = parent:CreateTexture(nil, layer or "ARTWORK")
    texture:SetSize(size or 16, size or 16)
    ns.SetIcon(texture, name)
    texture:SetVertexColor(0.86, 0.88, 0.93)
    return texture
end
`;
fs.writeFileSync(path.join(root, 'KutzUI/Icons.lua'), lua);
console.log(`OK Lucide: ${icons.length} icons, ${width}x${height} TGA, revision ${manifest.revision}`);
